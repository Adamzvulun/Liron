import { useLayoutEffect, useRef, useState, type ReactNode } from 'react';
import type { SubjectInfo } from '../subject.ts';
import { ARENA_SIGN, PLACE_LABELS, PLAQUES, STAGE, SUBJECT_BUILDINGS } from './layout.ts';
import { paintCity, type PaintedPart, type PlaceId } from './painter.js';
import './city.css';

// The painted scene never changes, so it is painted once per page load.
let painted: ReturnType<typeof paintCity> | undefined;
function scene() {
  if (!painted) {
    performance.mark('city:paint-start');
    painted = paintCity();
    performance.measure('city:paint', 'city:paint-start');
  }
  return painted;
}

/** Scale that fits the 1920×1080 stage inside the window without distorting it. */
function useStageScale() {
  const ref = useRef<HTMLDivElement>(null);
  const [scale, setScale] = useState(1);
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const fit = () =>
      setScale(Math.min(el.clientWidth / STAGE.width, el.clientHeight / STAGE.height));
    fit();
    const observer = new ResizeObserver(fit);
    observer.observe(el);
    return () => observer.disconnect();
  }, []);
  return [ref, scale] as const;
}

/** A full-stage SVG layer. The markup is generated by our own painter, never from user input. */
function Layer({ svg, className }: { svg: string; className?: string }) {
  return (
    <svg
      className={`city__layer ${className ?? ''}`}
      aria-hidden="true"
      width={STAGE.width}
      height={STAGE.height}
      viewBox={`0 0 ${STAGE.width} ${STAGE.height}`}
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}

function Part({ part }: { part: PaintedPart }) {
  const { x, y, w, h } = part.box;
  return (
    <svg
      className="city__part"
      aria-hidden="true"
      width={w}
      height={h}
      viewBox={`${x} ${y} ${w} ${h}`}
      style={{ left: x, top: y }}
      dangerouslySetInnerHTML={{ __html: part.svg }}
    />
  );
}

/**
 * The city square (issue #24): the approved concept v3, painted in the browser and scaled to
 * fit the window. `children` (the HUD) sit on top, outside the scaled stage.
 */
export function City({
  subjects,
  children,
}: {
  subjects: readonly SubjectInfo[];
  children?: ReactNode;
}) {
  const city = scene();
  const [ref, scale] = useStageScale();
  const residents = new Map<PlaceId, SubjectInfo>();
  for (const s of subjects) {
    const building = SUBJECT_BUILDINGS[s.id];
    if (building) residents.set(building, s);
  }
  return (
    <main className="city" ref={ref}>
      <h1 className="visually-hidden">Waymark</h1>
      <div
        className="city__stage"
        style={{
          width: STAGE.width,
          height: STAGE.height,
          transform: `translate(-50%, -50%) scale(${scale})`,
        }}
      >
        <Layer svg={`<defs>${city.defs}</defs>${city.layers.sky}`} />
        <Layer svg={city.layers.ground} />
        <Layer svg={city.layers.mid} />
        <div
          className="city__sign city__sign--arena"
          style={{ left: ARENA_SIGN.x, top: ARENA_SIGN.y }}
        >
          {ARENA_SIGN.text}
        </div>
        {(Object.keys(city.places) as PlaceId[]).map((id) => {
          const plaque = PLAQUES[id];
          const resident = residents.get(id);
          return (
            <section
              key={id}
              className={`city__place city__place--${id}`}
              aria-label={`${resident?.place ?? plaque.title}: ${resident?.tagline ?? PLACE_LABELS[id]}`}
            >
              <Part part={city.places[id]} />
              <h2
                className={`city__plaque${plaque.small ? ' city__plaque--small' : ''}`}
                style={{ left: plaque.x, top: plaque.y, width: plaque.width }}
              >
                {resident?.place ?? plaque.title}
                {id === 'caravanserai' && (
                  <span className="city__plaque-sub" lang="ar" dir="rtl">
                    الخان
                  </span>
                )}
              </h2>
            </section>
          );
        })}
        <div className="city__avatar" role="img" aria-label="Your character">
          <Part part={city.avatar} />
        </div>
        <Layer svg={city.layers.front} className="city__layer--front" />
      </div>
      <div className="city__overlay">{children}</div>
    </main>
  );
}
