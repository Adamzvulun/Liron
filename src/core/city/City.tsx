import { useEffect, useLayoutEffect, useRef, useState, type ReactNode } from 'react';
import { Link } from '../Link.tsx';
import type { SubjectInfo } from '../subject.ts';
import {
  ARENA_LOCKED,
  ARENA_SIGN,
  PLACE_LABELS,
  PLACE_PATHS,
  PLAQUES,
  residentsOf,
  STAGE,
  stageFit,
} from './layout.ts';
import { paintCity, type PaintedPart, type PlaceId } from './painter.js';
import './city.css';

/** Short names for the phone's dock, where space is tight. */
const DOCK_LABELS: Partial<Record<PlaceId, string>> = { board: 'Quests', house: 'House' };

// The painted scene never changes, so it is painted once per page load.
let painted: ReturnType<typeof paintCity> | undefined;
function scene() {
  if (!painted) {
    performance.mark('city:paint-start');
    painted = paintCity();
    performance.measure('city:paint', 'city:paint-start');
  }
  return painted;
}

/** On a phone held upright the scene fills the height and pans sideways (#27). */
const panning = (el: HTMLElement) => el.clientWidth < 900 && el.clientHeight > el.clientWidth;

/** Where the view starts when it pans: the compass in the middle of the square. */
const START_X = 1010;

/**
 * Scale and position for the 1920×1080 stage. Wide windows are filled (`stageFit`); upright
 * phones fill the height and scroll sideways, starting at the compass.
 */
function useStageScale() {
  const ref = useRef<HTMLDivElement>(null);
  const [view, setView] = useState({ scale: 1, x: 0, y: 0, pan: false });
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const fit = () => {
      const pan = panning(el);
      setView(
        pan
          ? { scale: el.clientHeight / STAGE.height, x: 0, y: 0, pan }
          : { ...stageFit(el.clientWidth, el.clientHeight), pan },
      );
    };
    fit();
    const observer = new ResizeObserver(fit);
    observer.observe(el);
    return () => observer.disconnect();
  }, []);
  // Keep the same spot of the square in the middle when the scale changes (the HUD loading
  // above shrinks the view); start at the compass.
  const centre = useRef(START_X);
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el || !view.pan) return;
    el.scrollLeft = centre.current * view.scale - el.clientWidth / 2;
    const remember = () => {
      centre.current = (el.scrollLeft + el.clientWidth / 2) / view.scale;
    };
    el.addEventListener('scroll', remember, { passive: true });
    return () => el.removeEventListener('scroll', remember);
  }, [view.pan, view.scale]);
  return [ref, view] as const;
}

/** A full-stage SVG layer. The markup is generated by our own painter, never from user input. */
function Layer({ svg, className }: { svg: string; className?: string }) {
  return (
    <svg
      className={`city__layer ${className ?? ''}`}
      aria-hidden="true"
      width={STAGE.width}
      height={STAGE.height}
      viewBox={`0 0 ${STAGE.width} ${STAGE.height}`}
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}

function Part({ part }: { part: PaintedPart }) {
  const { x, y, w, h } = part.box;
  return (
    <svg
      className="city__part"
      aria-hidden="true"
      width={w}
      height={h}
      viewBox={`${x} ${y} ${w} ${h}`}
      style={{ left: x, top: y }}
      dangerouslySetInnerHTML={{ __html: part.svg }}
    />
  );
}

/**
 * The city square (issue #24): the approved concept v3, painted in the browser and scaled to
 * fit the window. Each place is a link to its screen (#25). `children` (the HUD) sit on top,
 * outside the scaled stage.
 */
export function City({
  subjects,
  children,
}: {
  subjects: readonly SubjectInfo[];
  children?: ReactNode;
}) {
  const city = scene();
  const [ref, { scale, x, y, pan }] = useStageScale();
  const residents = residentsOf(subjects);
  const [knocked, setKnocked] = useState(false);
  useEffect(() => {
    if (!knocked) return;
    const t = setTimeout(() => setKnocked(false), 5000);
    return () => clearTimeout(t);
  }, [knocked]);
  return (
    <main className={`city${pan ? ' city--pan' : ''}`}>
      <h1 className="visually-hidden">Waymark</h1>
      <div className="city__view" ref={ref}>
        {pan && (
          <div
            className="city__sizer"
            style={{ width: STAGE.width * scale, height: STAGE.height * scale }}
          />
        )}
        <div
          className="city__stage"
          style={{
            width: STAGE.width,
            height: STAGE.height,
            transform: `translate(${x}px, ${y}px) scale(${scale})`,
          }}
        >
          <Layer svg={`<defs>${city.defs}</defs>${city.layers.sky}`} />
          <Layer svg={city.layers.ground} />
          <Layer svg={city.layers.mid} />
          <button
            type="button"
            className="city__sign city__sign--arena"
            style={{ left: ARENA_SIGN.x, top: ARENA_SIGN.y }}
            onClick={() => setKnocked(true)}
          >
            {ARENA_SIGN.text}
          </button>
          {city.plots.map((plot, i) => (
            <div
              key={i}
              className="city__plot"
              role="img"
              aria-label="An empty plot, where a new guild can build"
              title="An empty plot: a new guild can build here"
            >
              <Part part={plot} />
            </div>
          ))}
          {(Object.keys(city.places) as PlaceId[]).map((id) => {
            const plaque = PLAQUES[id];
            const resident = residents.get(id);
            return (
              <Link
                key={id}
                href={PLACE_PATHS[id]}
                className={`city__place city__place--${id}`}
                aria-label={`${resident?.place ?? plaque.title}: ${resident?.tagline ?? PLACE_LABELS[id]}`}
              >
                <Part part={city.places[id]} />
                <h2
                  className={`city__plaque${plaque.small ? ' city__plaque--small' : ''}`}
                  style={{ left: plaque.x, top: plaque.y, width: plaque.width }}
                >
                  {resident?.place ?? plaque.title}
                  {id === 'caravanserai' && (
                    <span className="city__plaque-sub" lang="ar" dir="rtl">
                      الخان
                    </span>
                  )}
                </h2>
              </Link>
            );
          })}
          <div className="city__avatar" role="img" aria-label="Your character">
            <Part part={city.avatar} />
          </div>
          <Layer svg={city.layers.front} className="city__layer--front" />
        </div>
      </div>
      {pan && (
        <nav className="city__dock" aria-label="Places">
          {(Object.keys(city.places) as PlaceId[]).map((id) => (
            <Link
              key={id}
              href={PLACE_PATHS[id]}
              className="city__dockitem"
              style={{ borderTopColor: residents.get(id)?.guildColor }}
            >
              {DOCK_LABELS[id] ?? residents.get(id)?.place ?? PLAQUES[id].title}
            </Link>
          ))}
        </nav>
      )}
      <div className="city__overlay">
        {children}
        <p className="city__notice" role="status">
          {knocked && ARENA_LOCKED}
        </p>
      </div>
    </main>
  );
}
